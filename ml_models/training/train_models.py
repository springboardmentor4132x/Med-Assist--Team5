"""
MedAssist AI - Module 3: Machine Learning Model Training
Script: ml_models/training/train_models.py
Responsibility: Member 2 - Model Training

What this script does:
    1. Loads the cleaned dataset prepared by Member 1 (dataset/processed/).
    2. Separates symptom/profile features from the targets.
    3. Splits the data into training and testing sets (same split is used
       later by the evaluation script).
    4. Trains five classifiers for each of the two prediction tasks:
           Decision Tree, Random Forest, SVM, XGBoost, Logistic Regression
    5. Saves every trained model (preprocessing + classifier in one
       pipeline) to ml_models/trained_models/<task>/<model>.joblib
    6. Writes ml_models/reports/model_training_report.md

Tasks:
    disease  -> predict the disease name (116 classes)  [module brief]
    outcome  -> predict Positive/Negative outcome        [handoff target]

Usage (from the project root):
    python ml_models/training/train_models.py
"""

import json
import sys
import time
from pathlib import Path

import joblib
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from ml_models.common import (  # noqa: E402
    FEATURE_COLS,
    MODEL_LABELS,
    MODEL_NAMES,
    RANDOM_STATE,
    REPORTS_DIR,
    TASKS,
    TRAINED_DIR,
    build_model,
    encode_target,
    load_data,
    make_split,
    predict_labels,
    top_k_accuracy,
)


def train_task(df, task):
    """Train all models for one task and return a list of result rows."""
    y, encoder = encode_target(df, task)
    train_idx, test_idx = make_split(df, y, task)

    X = df[FEATURE_COLS]
    X_train, y_train = X.iloc[train_idx], y[train_idx]
    X_test, y_test = X.iloc[test_idx], y[test_idx]

    out_dir = TRAINED_DIR / task
    out_dir.mkdir(parents=True, exist_ok=True)
    joblib.dump(encoder, out_dir / "label_encoder.joblib")
    (out_dir / "feature_columns.json").write_text(
        json.dumps(FEATURE_COLS, indent=2), encoding="utf-8"
    )

    print(f"\n=== Task: {task} ===")
    print(f"classes: {len(encoder.classes_)} | train rows: {len(train_idx)} "
          f"| test rows: {len(test_idx)}")

    rows = []
    for name in MODEL_NAMES:
        model = build_model(name, task)
        start = time.time()
        model.fit(X_train, y_train)
        seconds = time.time() - start

        classes = model.classes_
        train_acc = float(np.mean(predict_labels(model, X_train) == y_train))
        test_acc = float(np.mean(predict_labels(model, X_test) == y_test))
        test_top3 = top_k_accuracy(model.predict_proba(X_test), classes, y_test, 3)

        joblib.dump(model, out_dir / f"{name}.joblib")
        size_kb = (out_dir / f"{name}.joblib").stat().st_size / 1024

        top3_text = f" top3={test_top3:.3f}" if task == "disease" else ""
        print(f"  {MODEL_LABELS[name]:<20} train={train_acc:.3f} "
              f"test={test_acc:.3f}{top3_text} "
              f"({seconds:.1f}s, {size_kb:.0f} KB)")
        rows.append(
            {
                "model": name,
                "train_accuracy": train_acc,
                "test_accuracy": test_acc,
                "test_top3": test_top3,
                "seconds": seconds,
                "size_kb": size_kb,
            }
        )
    return rows, len(encoder.classes_), len(train_idx), len(test_idx)


def write_report(results):
    lines = [
        "# Model Training Report",
        "## MedAssist AI - Module 3 (Member 2: Model Training)",
        "",
        "Generated by `ml_models/training/train_models.py`. Every model is a",
        "scikit-learn `Pipeline` (preprocessing + classifier), so the saved file",
        "accepts raw patient columns and applies the exact same encoding that",
        "was used in training.",
        "",
        "## 1. Input features",
        "",
        f"`{', '.join(FEATURE_COLS)}`",
        "",
        "- Symptoms (`fever`, `cough`, `fatigue`, `difficulty_breathing`): already 0/1.",
        "- `age`: numeric (standardised for SVM and Logistic Regression only).",
        "- `gender`, `blood_pressure`, `cholesterol_level`: one-hot encoded inside the pipeline.",
        "- Split: 80% train / 20% test, `random_state=42`.",
        "",
        "## 2. Models trained",
        "",
        "| Model | Key settings |",
        "| :--- | :--- |",
        "| Decision Tree | `max_depth` 6 (outcome) / 12 (disease), `min_samples_leaf` 3 / 1 |",
        "| Random Forest | 300 trees (outcome) / 100 trees, `max_depth` 8 (disease); `min_samples_leaf=2` |",
        "| SVM | RBF kernel, `C=1`, `probability=True` (gives probability scores) |",
        "| XGBoost | 100 trees, `max_depth=3`, `learning_rate=0.1` |",
        "| Logistic Regression | `max_iter=3000` (linear baseline) |",
        "",
        "All models support `predict_proba`, which Member 4 needs for the top 3",
        "predictions and the probability scores.",
        "",
    ]

    titles = {
        "disease": "## 3. Disease classification (116 diseases)",
        "outcome": "## 4. Outcome classification (Positive / Negative)",
    }
    for task, (rows, n_classes, n_train, n_test) in results.items():
        show_top3 = task == "disease"  # top-3 means nothing with 2 classes
        lines += [
            titles[task],
            "",
            f"Classes: {n_classes} | Training rows: {n_train} | Test rows: {n_test}",
            "",
            "| Model | Train accuracy | Test accuracy |"
            + (" Test top-3 accuracy |" if show_top3 else "")
            + " Train time (s) | File size (KB) |",
            "| :--- | ---: | ---: |" + (" ---: |" if show_top3 else "") + " ---: | ---: |",
        ]
        for r in rows:
            lines.append(
                f"| {MODEL_LABELS[r['model']]} | {r['train_accuracy']:.3f} | "
                f"{r['test_accuracy']:.3f} |"
                + (f" {r['test_top3']:.3f} |" if show_top3 else "")
                + f" {r['seconds']:.1f} | {r['size_kb']:.0f} |"
            )
        lines.append("")

    lines += [
        "## 5. Notes",
        "",
        "- These are quick train/test numbers from one split. The test sets are small,",
        "  so the proper comparison (cross-validation, precision, recall, F1,",
        "  confusion matrices) is done by Member 3 in",
        "  `ml_models/reports/model_evaluation_report.md`.",
        "- Diseases with only one record in the dataset are always placed in the",
        "  training set (a single record cannot be in both train and test).",
        "- A large gap between train and test accuracy means overfitting; the",
        "  dataset has only 300 rows, so this is expected for the deeper models.",
        "- Model outputs are preliminary decision-support scores, not medical diagnoses.",
        "",
        "## 6. How to re-run",
        "",
        "```bash",
        "pip install pandas scikit-learn xgboost joblib matplotlib",
        "python ml_models/training/train_models.py",
        "```",
    ]
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "model_training_report.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )


def main():
    print("=" * 70)
    print("MEDASSIST AI - MODEL TRAINING (MODULE 3, MEMBER 2)")
    print("=" * 70)
    np.random.seed(RANDOM_STATE)
    df = load_data()
    print(f"Loaded {df.shape[0]} rows x {df.shape[1]} columns")

    results = {}
    for task in TASKS:
        results[task] = train_task(df, task)

    write_report(results)
    print("\nModels saved in:", TRAINED_DIR)
    print("Report saved in:", REPORTS_DIR / "model_training_report.md")


if __name__ == "__main__":
    main()
